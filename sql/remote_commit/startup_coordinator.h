inline constexpr size_t kStartupBootstrapPreflightMaxBytes =
    kMaxCanonicalGtidBytes + 64 * 1024;
inline constexpr size_t kStartupWorkerRequestMaxBytes =
    kRecoveryManifestBytesMax;
inline constexpr size_t kStartupWorkerEvidenceMaxBytes =
    kSnapshotManifestMaxBytes + 64 * 1024 * 1024;
inline constexpr size_t kStartupRestartProofMaxBytes =
    kMaxCanonicalGtidBytes + kHeadMaxBytes + kWriterEpochMaxBytes +
    kLocalInstallMarkerMaxBytes + 64 * 1024;

enum class StartupCoordinatorRoute : uint8_t {
  BOOTSTRAP,
  TAKEOVER,
};

enum class StartupCoordinatorState : uint8_t {
  STARTING,
  INITIALIZING,
  RECOVERING,
  WORKER_REQUIRED,
  SNAPSHOT_PUBLISHED,
  ROOT_INSTALLED,
  RESTART_REQUIRED,
  POST_ENGINE_VERIFICATION_REQUIRED,
  ACTIVATED,
  FAILED_CLOSED,
  FENCED,
};

enum class StartupCoordinatorOutcome : uint8_t {
  READY_FOR_ADMISSION,
  WORKER_REQUIRED,
  POST_ENGINE_VERIFICATION_REQUIRED,
  BLOCKED,
  CORRUPT,
  FOREIGN_OR_CORRUPT,
  LOCAL_IO_ERROR,
  UNSUPPORTED,
  RESTART_REQUIRED,
  FENCED,
};

enum class StartupStepOutcome : uint8_t {
  READY,
  BLOCKED,
  CORRUPT,
  LOCAL_IO_ERROR,
  RESTART_REQUIRED,
  FENCED,
};

struct StartupStepResult {
  StartupStepOutcome outcome{StartupStepOutcome::CORRUPT};
  std::string detail;

  bool ready() const { return outcome == StartupStepOutcome::READY; }
};

struct StartupDeploymentIdentity {
  std::string stream_id;
  std::string server_uuid;
  DeploymentFingerprints fingerprints;
  // SHA-256 over the externally supplied binary/plugin identity used by the
  // local marker. The constituent fingerprints remain in the remote snapshot.
  std::string binary_fingerprint;

  bool operator==(const StartupDeploymentIdentity &) const = default;
};

// Evidence captured while an engine-owning worker has the fresh root open.
// marker_matches and snapshot_matches are required only from the re-exec
// process after the installed root has been activated and its engines opened.
struct StartupRootEvidence {
  Cursor recovered_cursor;
  GtidSetDigest recovered_gtid;
  bool marker_matches{false};
  bool snapshot_matches{false};
  bool server_uuid_matches{false};
  bool configuration_matches{false};
  bool gtid_matches{false};
  bool dd_matches{false};
  bool repository_empty{false};
  bool extent_live_set_matches{false};
  uint64_t exported_extent_count{0};
  std::string exported_extent_set_sha256;
  bool internal_prepared_empty{false};
  bool external_xa_empty{false};
};

// startup_server creates this only after a HEAD-absent initialize-insecure
// child exits cleanly. Its root is the exact root later handed to the export
// worker; neither the coordinator nor the worker may initialize another root.
struct StartupBootstrapPreflight {
  std::filesystem::path root;
  std::string request_nonce;
  std::string request_sha256;
  bool child_exited_cleanly{false};
  // Exact identity observed from the initialized root. The parent cannot know
  // the generated server UUID before initialize-insecure completes.
  StartupDeploymentIdentity initialized_deployment;
  bool dd_initialized{false};
  bool repository_empty{false};
  bool internal_prepared_empty{false};
  bool external_xa_empty{false};
  bool empty_source_scan_stable{false};
  bool old_tc_authority_empty{false};
  bool user_state_empty{false};
  bool legacy_live_extents_empty{false};
};

struct StartupCoordinatorOptions {
  std::filesystem::path target_root;
  MaterializeOptions materialize;
  StartupDeploymentIdentity deployment;
  // A fresh, unpredictable lowercase SHA-256-sized nonce generated by the
  // process adapter. It binds a worker completion to this exact preparation.
  std::string worker_nonce;
  std::optional<StartupBootstrapPreflight> bootstrap_preflight;
};

struct StartupActivationOptions {
  std::filesystem::path target_root;
  StartupDeploymentIdentity deployment;
};

// Cached result of the server hook's mutation-free HEAD-first probe. A
// takeover probe carries the exact HEAD observed before any epoch acquisition;
// a bootstrap probe carries no HEAD identity.
struct StartupHookProbe {
  StartupCoordinatorRoute route{StartupCoordinatorRoute::TAKEOVER};
  PublishedBytes head_object;
  uint64_t head_generation{0};
  Cursor durable_cursor;
};

struct ExactWriterEpoch {
  PublishedBytes object;
  WriterEpoch value;
};

struct PublishedStartupHead {
  PublishedBytes object;
  Head value;
};

struct StartupCandidateBoundary {
  PublishedStartupHead head;
  Cursor replay_exclusive_start;
  Cursor replay_inclusive_end;
};

// This is an owned, bounded cross-process request. The worker exact-reads the
// candidate identified by candidate.head before replay. It opens only root,
// performs route-specific work, exports every snapshot payload under epoch,
// fsyncs those files, captures a FixedSnapshotCut, and exits. It must not
// publish HEAD, install root, open networking, or admit writes.
struct StartupWorkerRequest {
  StartupCoordinatorRoute route{StartupCoordinatorRoute::TAKEOVER};
  std::string request_nonce;
  std::string request_sha256;
  std::filesystem::path root;
  StartupDeploymentIdentity deployment;
  ExactWriterEpoch epoch;
  std::optional<StartupCandidateBoundary> candidate;
  std::optional<MaterializedRoot> materialized;
};

// The parent may construct this only after waitpid reports a clean worker
// exit and its bounded evidence transport has been authenticated. The copied
// FixedSnapshotCut is the only cut publication may consume; it must not be
// resampled after the worker has closed its engines.
struct StartupWorkerCompletion {
  bool child_exited_cleanly{false};
  std::string request_nonce;
  std::string request_sha256;
  StartupRootEvidence root_evidence;
  FixedSnapshotCut snapshot_cut;
};

struct StartupSnapshotPublishRequest {
  StartupCoordinatorRoute route;
  const std::filesystem::path &root;
  const StartupDeploymentIdentity &deployment;
  const ExactWriterEpoch &epoch;
  const StartupRootEvidence &root_evidence;
  const FixedSnapshotCut &snapshot_cut;
  // Non-null for takeover. Publication must use this exact HEAD body and ETag
  // as its parent and must never take a late cursor or engine-state sample.
  const RecoveryPlan *candidate;
};

// Bounded payload written by startup_server to a private sibling file. It is
// deliberately not carried in argv or the environment because canonical GTID
// text can be large. The file is transport-only and is not installed in root.
struct StartupRestartProof {
  StartupCoordinatorRoute route{StartupCoordinatorRoute::TAKEOVER};
  StartupDeploymentIdentity deployment;
  PublishedStartupHead head;
  ExactWriterEpoch epoch;
  LocalInstallMarker marker;
  StartupRootEvidence expected_root;
  // The first manifest is captured immediately after the clean worker exit and
  // rechecked after publication. The second is captured after atomic install;
  // it may differ only by the canonical local install marker.
  StartupStableRootManifest stopped_worker_root;
  StartupStableRootManifest installed_root;
};

// startup_server owns this file. It keeps it through exec, exact-reads and
// authenticates it on re-exec, then unlinks it after the payload is adopted.
// A failed adoption leaves the installed root and first-failure evidence intact.
struct StartupRestartProofReference {
  std::filesystem::path path;
  uint64_t size{0};
  std::string sha256;
};

struct StartupActivationRequest {
  StartupCoordinatorRoute route;
  const RecoveryPlan &published;
  const ExactWriterEpoch &epoch;
  const LocalInstallMarker &marker;
  const StartupRootEvidence &expected_root;
  const StartupStableRootManifest &stopped_worker_root;
  const StartupStableRootManifest &installed_root;
};

struct StartupCoordinatorProof {
  PublishedStartupHead head;
  ExactWriterEpoch epoch;
  LocalInstallMarker marker;
  StartupRootEvidence installed_root;
  StartupStableRootManifest installed_root_manifest;
};

struct StartupCoordinatorResult {
  StartupCoordinatorOutcome outcome{StartupCoordinatorOutcome::CORRUPT};
  std::string detail;
  std::optional<StartupWorkerRequest> worker_request;
  std::optional<StartupRestartProofReference> restart_proof;
  std::optional<StartupCoordinatorProof> proof;

  bool worker_required() const {
    return outcome == StartupCoordinatorOutcome::WORKER_REQUIRED &&
           worker_request.has_value() && !restart_proof.has_value() &&
           !proof.has_value();
  }

  bool restart_required() const {
    return outcome == StartupCoordinatorOutcome::RESTART_REQUIRED &&
           !worker_request.has_value() && restart_proof.has_value() &&
           !proof.has_value();
  }

  bool post_engine_verification_required() const {
    return outcome ==
               StartupCoordinatorOutcome::POST_ENGINE_VERIFICATION_REQUIRED &&
           !worker_request.has_value() && !restart_proof.has_value() &&
           !proof.has_value();
  }

  bool ready_for_admission() const {
    return outcome == StartupCoordinatorOutcome::READY_FOR_ADMISSION &&
           !worker_request.has_value() && !restart_proof.has_value() &&
           proof.has_value();
  }
};

