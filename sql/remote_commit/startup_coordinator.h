// Operations that require server/runtime integration but never require the
// parent coordinator to own live engine objects. Worker execution and evidence
// collection happen outside this interface.
class StartupCoordinatorOperations {
 public:
  virtual ~StartupCoordinatorOperations() = default;

  virtual StartupStepResult startup_probe(StartupHookProbe *probe) = 0;
  virtual StartupStepResult acquire_epoch(ExactWriterEpoch *epoch) = 0;
  virtual StartupStepResult publish_snapshot(
      const StartupSnapshotPublishRequest &request,
      PublishedStartupHead *published) = 0;
  virtual StartupStepResult persist_restart_proof(
      const StartupRestartProof &proof,
      StartupRestartProofReference *reference) = 0;
  // Called by the re-exec process before stock TC/binlog recovery. It grants
  // only installed-root recovery activation; admission remains closed until
  // finish_post_engine_verification() returns READY_FOR_ADMISSION.
  virtual StartupStepResult activate_installed_root(
      const StartupActivationRequest &request) = 0;
};

// Storage operations are split out so the ordering state machine can be tested
// without an object-store service. The default implementation is the
// production adapter over the bounded reader, fresh-root materializer, and
// crash-safe local installer.
class StartupCoordinatorStorage {
 public:
  virtual ~StartupCoordinatorStorage() = default;

  virtual RecoveryReadResult read(RecoveryPlan *plan) = 0;
  virtual TargetClassification classify(
      const std::filesystem::path &target,
      const LocalInstallMarker &expected_deployment,
      bool allow_managed_replace) = 0;
  virtual MaterializeResult materialize(const RecoveryPlan &plan,
                                        const MaterializeOptions &options,
                                        MaterializedRoot *root) = 0;
  virtual InstallResult install(const std::filesystem::path &temporary_root,
                                const std::filesystem::path &target,
                                const LocalInstallMarker &expected_marker,
                                bool allow_managed_replace) = 0;
  virtual StartupStepResult snapshot_stopped_root(
      const std::filesystem::path &root, StartupRootSnapshot *snapshot) = 0;
};

class DefaultStartupCoordinatorStorage final
    : public StartupCoordinatorStorage {
 public:
  DefaultStartupCoordinatorStorage(ConditionalIo *conditional_io,
                                   PayloadIo *payload_io,
                                   BinlogImageValidator *binlog_validator,
                                   StreamIdentity stream)
      : reader_(conditional_io, std::move(stream)),
        materializer_(payload_io, binlog_validator) {}

  RecoveryReadResult read(RecoveryPlan *plan) override;
  TargetClassification classify(
      const std::filesystem::path &target,
      const LocalInstallMarker &expected_deployment,
      bool allow_managed_replace) override;
  MaterializeResult materialize(const RecoveryPlan &plan,
                                const MaterializeOptions &options,
                                MaterializedRoot *root) override;
  InstallResult install(const std::filesystem::path &temporary_root,
                        const std::filesystem::path &target,
                        const LocalInstallMarker &expected_marker,
                        bool allow_managed_replace) override;
  StartupStepResult snapshot_stopped_root(
      const std::filesystem::path &root,
      StartupRootSnapshot *snapshot) override;

 private:
  RecoveryChainReader reader_;
  RecoveryMaterializer materializer_;
};

class StartupCoordinator {
 public:
  StartupCoordinator(StreamIdentity stream, StartupCoordinatorStorage *storage,
                     StartupCoordinatorOperations *operations)
      : stream_(std::move(stream)),
        storage_(storage),
        operations_(operations) {}

  // Parent phase. Performs HEAD-first preparation and returns one bounded
  // worker request. BOOTSTRAP requires an already completed initialize-insecure
  // preflight; TAKEOVER materializes the exact epoch-bound candidate first.
  StartupCoordinatorResult prepare_worker(
      const StartupCoordinatorOptions &options);

  // Parent phase. Called only after the requested worker exits cleanly. It
  // publishes the worker's exact cut, installs the now-closed stable root,
  // persists a bounded restart proof, and requires exec. It never reopens root.
  StartupCoordinatorResult finish_worker(
      const StartupWorkerCompletion &completion);

  // Re-exec phase, on a fresh coordinator instance. startup_server has already
  // authenticated and parsed the referenced proof. This method exact-rechecks
  // remote HEAD/epoch and the installed marker, then activates root before
  // stock TC/binlog recovery.
  StartupCoordinatorResult adopt_restart_proof(
      const StartupActivationOptions &options,
      const StartupRestartProof &proof);

  // Re-exec post-engine phase. The caller supplies authoritative installed-root
  // evidence only after engines are open. Admission may open only on success.
  StartupCoordinatorResult finish_post_engine_verification(
      const StartupRootEvidence &installed_evidence);

  StartupCoordinatorState state() const { return state_; }
  std::optional<StartupCoordinatorRoute> route() const { return route_; }
  const RecoveryPlan *candidate() const {
    return candidate_.has_value() ? &*candidate_ : nullptr;
  }
  const RecoveryPlan *published() const {
    return published_.has_value() ? &*published_ : nullptr;
  }
  const LocalInstallMarker *installed_marker() const {
    return marker_.has_value() ? &*marker_ : nullptr;
  }

 private:
  StartupCoordinatorResult fail(StartupCoordinatorOutcome outcome,
                                std::string detail);
  StartupCoordinatorResult fail(const StartupStepResult &step,
                                std::string_view operation);

  StreamIdentity stream_;
  StartupCoordinatorStorage *storage_;
  StartupCoordinatorOperations *operations_;
  StartupCoordinatorState state_{StartupCoordinatorState::STARTING};
  std::optional<StartupCoordinatorRoute> route_;
  std::optional<StartupCoordinatorOptions> options_;
  std::optional<StartupActivationOptions> activation_options_;
  std::optional<StartupHookProbe> hook_probe_;
  std::optional<ExactWriterEpoch> acquired_;
  std::optional<RecoveryPlan> candidate_;
  std::optional<MaterializedRoot> materialized_;
  std::optional<StartupRootEvidence> root_evidence_;
  std::optional<RecoveryPlan> published_;
  std::optional<LocalInstallMarker> marker_;
  std::optional<StartupRestartProof> restart_proof_;
  std::optional<StartupStableRootManifest> stopped_worker_root_;
  std::optional<StartupStableRootManifest> installed_root_manifest_;
  bool installed_root_verified_{false};
  std::string worker_nonce_;
  std::string worker_request_sha256_;
};

